	/**
	 * Configures settings for Subject Permissions.
	 *
	 * @param {Object} settings - The settings object
	 * @param {boolean} [settings.SelfEvaluation] - Enable self-evaluation
	 * @param {boolean|Object} [settings.ChooseEvaluators] - Allow choosing evaluators
	 *   - If boolean: simple toggle
	 *   - If object: { enabled: boolean, restrictRoles: boolean, selectRoles: string[], checkRoles: boolean }
	 * @param {boolean} [settings.ApprovalApprover] - Require approval of approver
	 * @param {boolean} [settings.ReportApproval] - Require report approval
	 * @param {boolean} [settings.RestrictSubjectReport] - Restrict subject's access to report
	 * @param {boolean|string|Object} [settings.AllowSubjectToAddGuestUsers] - Allow subject to add guest users
	 *   - true: enable checkbox only
	 *   - "anyRole": enable and select "any role" option
	 *   - "guestRole": enable and select "guest role only" option
	 *   - { option: "anyRole"|"guestRole", GuestRoleEnabled: boolean }: object format
	 *     - GuestRoleEnabled: if true, skips the alert dialog check (Guest role already enabled)
	 *
	 * @example
	 * // Single setting
	 * await configurePage.configureSettingsCheckSubjectPermissions({
	 *   SelfEvaluation: true
	 * });
	 *
	 * @example
	 * // Multiple settings
	 * await configurePage.configureSettingsCheckSubjectPermissions({
	 *   SelfEvaluation: true,
	 *   ChooseEvaluators: true,
	 *   ApprovalApprover: false,
	 *   AllowSubjectToAddGuestUsers: "guestRole"
	 * });
	 *
	 * @example
	 * // ChooseEvaluators with nested options
	 * await configurePage.configureSettingsCheckSubjectPermissions({
	 *   SelfEvaluation: true,
	 *   ChooseEvaluators: {
	 *     enabled: true,
	 *     restrictRoles: true,
	 *     selectRoles: ["Peer", "Manager"],
	 *     checkRoles: true
	 *   },
	 *   AllowSubjectToAddGuestUsers: "guestRole"
	 * });
	 *
	 * @example
	 * // AllowSubjectToAddGuestUsers with GuestRoleEnabled (skip alert check)
	 * await configurePage.configureSettingsCheckSubjectPermissions({
	 *   AllowSubjectToAddGuestUsers: {
	 *     option: "guestRole",
	 *     GuestRoleEnabled: true  // Guest role already enabled, skip alert
	 *   }
	 * });
	 */

	async configureSettingsCheckSubjectPermissions(settings = {}) {
		const {
			SelfEvaluation,
			ChooseEvaluators,
			ApprovalApprover,
			ReportApproval,
			RestrictSubjectReport,
			AllowSubjectToAddGuestUsers,
		} = settings;
		await PwActions.click(this.page, this.btnPermissions);
		if (SelfEvaluation !== undefined) {
			await CommonUtils.sleep(2);
			await PwActions.toggleCheckBox(
				this.page,
				SelfEvaluation,
				this.chkboxSelfEvaluation,
			);
		}

		if (ChooseEvaluators !== undefined) {
			await CommonUtils.sleep(2);

			if (typeof ChooseEvaluators === "boolean") {
				await PwActions.toggleCheckBox(
					this.page,
					ChooseEvaluators,
					this.chkboxChooseEvaluators,
				);
			} else if (
				typeof ChooseEvaluators === "object" &&
				ChooseEvaluators !== null
			) {
				const {
					enabled = true,
					restrictRoles = false,
					selectRoles = undefined,
					checkRoles = true,
				} = ChooseEvaluators;

				await PwActions.toggleCheckBox(
					this.page,
					enabled,
					this.chkboxChooseEvaluators,
				);

				if (enabled === true) {
					if (restrictRoles) {
						await PwActions.toggleCheckBox(
							this.page,
							true,
							this.chkboxRestrictSubjectFromNominatingParticularRoles,
						);
						await CommonUtils.sleep(2);
					}

					if (selectRoles !== undefined) {
						await PwActions.click(
							this.page,
							this.chkboxSelectEvaluatorRoleThatCanBeNominatedBySubject,
						);
						await CommonUtils.sleep(2);

						if (Array.isArray(selectRoles)) {
							for (const role of selectRoles) {
								const availableRoles = await this.page.$$eval(
									this.listofItems,
									(elements) => elements.map((el) => el.textContent.trim()),
								);

								if (availableRoles.includes(role)) {
									const isChecked = await this.page.isChecked(
										this.menuOptionCheck(role),
									);
									if (isChecked !== true) {
										await this.page
											.locator(this.menuOptionCheck(role))
											.click({ force: true });
									}
									await CommonUtils.sleep(1);
								}

								await CommonUtils.sleep(2);
							}
						}

						await PwActions.click(
							this.page,
							"//div[@role='menu']//span[text()='Apply']",
						);

						if (
							Array.isArray(selectRoles) &&
							selectRoles.includes("Guest") &&
							checkRoles
						) {
							await expect
								.soft(
									PwActions.waitTillVisible(
										this.page,
										this.btnYesEnableGuestRole,
										5000,
									),
								)
								.resolves.not.toThrow();
							await expect
								.soft(PwActions.click(this.page, this.btnYesEnableGuestRole))
								.resolves.not.toThrow();
						}
						await CommonUtils.sleep(2);
					}
				}
			}
		}

		if (ApprovalApprover !== undefined) {
			await CommonUtils.sleep(2);
			await PwActions.toggleCheckBox(
				this.page,
				ApprovalApprover,
				this.chkboxApprovalApprover,
			);
		}

		if (ReportApproval !== undefined) {
			await CommonUtils.sleep(2);
			await PwActions.toggleCheckBox(
				this.page,
				ReportApproval,
				this.chkboxReportApproval,
			);
		}

		if (RestrictSubjectReport !== undefined) {
			await PwActions.toggleCheckBox(
				this.page,
				RestrictSubjectReport,
				this.chkboxRestrictSubjectReport,
			);
		}

		if (AllowSubjectToAddGuestUsers !== undefined) {
			let roleOption;
			let guestRoleEnabled = false;

			if (
				typeof AllowSubjectToAddGuestUsers === "object" &&
				AllowSubjectToAddGuestUsers !== null
			) {
				roleOption = AllowSubjectToAddGuestUsers.option;
				guestRoleEnabled =
					AllowSubjectToAddGuestUsers.GuestRoleEnabled || false;
			} else {
				roleOption = AllowSubjectToAddGuestUsers;
			}

			const shouldEnable =
				roleOption === true ||
				roleOption === "anyRole" ||
				roleOption === "guestRole";

			await PwActions.toggleCheckBox(
				this.page,
				shouldEnable,
				this.chkboxAllowSubjectToAddGuestUsers,
			);
			await CommonUtils.sleep(2);

			if (shouldEnable) {
				if (roleOption === "anyRole") {
					await PwActions.toggleCheckBox(
						this.page,
						true,
						this.chkboxAllowSubjectToNominateGuestUsersToAnyRole,
					);
				} else if (roleOption === "guestRole") {
					await PwActions.toggleCheckBox(
						this.page,
						true,
						this.chkboxAllowSubjectToOnlyNominateGuestUsersAsGuestRole,
					);
					if (!guestRoleEnabled) {
						await CommonUtils.sleep(1);
						const isAlertVisible = await PwActions.elementIsVisible(
							this.page,
							this.btnYesEnableGuestRole,
						);
						if (isAlertVisible) {
							await PwActions.click(this.page, this.btnYesEnableGuestRole);
						}
					}
				}
			}
			await CommonUtils.sleep(2);
		}

		await CommonUtils.sleep(2);
	}

