	/**
	 * Configures the show survey in language settings
	 * @param {object} options - The options for the show survey in language settings
	 * @param {boolean} options.sourceLanguage - Whether to show the survey in the source language
	 * @param {boolean} options.preferredLanguage - Whether to show the survey in the preferred language
	 * @param {boolean} options.respondentsCanSwitchBetweenTranslations - Whether to allow respondents to switch between translations
	 * @example
	 * await configurePage.configureShowSurveyInLanguage({ sourceLanguage: true, preferredLanguage: false, respondentsCanSwitchBetweenTranslations: false });
	 * await configurePage.configureShowSurveyInLanguage({ sourceLanguage: false, preferredLanguage: true, respondentsCanSwitchBetweenTranslations: false });
	 */
	async configureShowSurveyInLanguage({
		page = this.page,
		sourceLanguage,
		preferredLanguage,
		respondentsCanSwitchBetweenTranslations,
	}) {
		if (sourceLanguage && preferredLanguage) {
			throw new Error(
				"Both sourceLanguage and preferredLanguage cannot be true.",
			);
		}
		await CommonUtils.sleep(2);
		if (await PwActions.elementIsVisible(page, this.btnLanguages)) {
			await PwActions.click(page, this.btnLanguages);
		}
		const [currentStateSource, currentStatePreferred, currentStateSwitch] =
			await Promise.all([
				PwActions.getAttributeValue(
					page,
					this.radioButtonSourceLanguage,
					"data-state",
				),
				PwActions.getAttributeValue(
					page,
					this.radioButtonRespondentsPreferredLanguage,
					"data-state",
				),
				PwActions.getAttributeValue(
					page,
					this.radioButtonCanSwitchBetweenTranslations,
					"data-state",
				),
			]);
		const radioButtons = [
			{
				selector: this.radioButtonSourceLanguage,
				current: currentStateSource === "checked",
				desired: sourceLanguage,
			},
			{
				selector: this.radioButtonRespondentsPreferredLanguage,
				current: currentStatePreferred === "checked",
				desired: preferredLanguage,
			},
		];
		for (const radioButton of radioButtons) {
			if (radioButton.desired === true && !radioButton.current) {
				await PwActions.click(page, radioButton.selector);
			}
		}
		const currentSwitchState = currentStateSwitch === "checked";
		if (
			respondentsCanSwitchBetweenTranslations !== undefined &&
			currentSwitchState !== respondentsCanSwitchBetweenTranslations
		) {
			await PwActions.click(page, this.radioButtonCanSwitchBetweenTranslations);
		}
	}

