	/**
	 * Configures the evaluator anonymity settings
	 * @param {object} anonymitySettings - The anonymity settings to configure
	 * @param {string} anonymitySettings.anonymity - The anonymity type ("Anonymous" | "Non Anonymous")
	 * @param {boolean} [anonymitySettings.showNameOrRole] - Whether to show name/role of evaluators in feedback report
	 * - For "Non Anonymous": selects "Show [Roles/Names] of the evaluators" or "Do not show roles and names"
	 * - For "Anonymous": selects "Show roles of the evaluators" or "Do not show roles of the evaluators"
	 * @param {string} [anonymitySettings.roleOrName] - What to display ("Roles" | "Names"). Only applicable when anonymity is "Non Anonymous" and showNameOrRole is true
	 * @param {Array<{question: string, anonymity: string}>} [anonymitySettings.override] - Question-specific anonymity overrides
	 * @example
	 * // Non Anonymous with Names shown
	 * await configurePage.configureSettingsSetEvaluatorAnonymity({
	 *   anonymitySettings: { anonymity: "Non Anonymous", showNameOrRole: true, roleOrName: "Names" }
	 * });
	 * @example
	 * // Anonymous with roles shown
	 * await configurePage.configureSettingsSetEvaluatorAnonymity({
	 *   anonymitySettings: { anonymity: "Anonymous", showNameOrRole: true }
	 * });
	 */
	async configureSettingsSetEvaluatorAnonymity({
		anonymitySettings,
		page = this.page,
	}) {
		const { anonymity, showNameOrRole, roleOrName, override } =
			anonymitySettings ?? {};
		const updateAnonymityDialog = `//p[text()="Update Anonymity Settings"]`;
		const isAnonymous = anonymity === "Anonymous";

		await PwActions.click(page, this.sideBarAnonymity);

		if (anonymity) {
			await PwActions.waitAndClick(page, this.dropdownAnonymity);
			await PwActions.waitAndClick(
				page,
				isAnonymous ? this.optionAnonymus : this.optionNonAnonymous,
			);
			await PwActions.waitForNetworkIdle(page, 20000);
			await PwActions.waitForElement(page, updateAnonymityDialog);
			if (await PwActions.elementIsVisible(page, updateAnonymityDialog)) {
				await PwActions.waitAndClick(
					page,
					this.btnConfirmAndApplyOverrideAnonymity,
				);
			}
			await CommonUtils.sleep(2);
		}

		const targetRadioBtn = this.getAnonymityRadioButton(
			isAnonymous,
			showNameOrRole,
		);
		if (
			(await PwActions.getAttributeValue(
				page,
				targetRadioBtn,
				"aria-checked",
			)) !== "true"
		) {
			await PwActions.waitForNetworkIdle(page, 20000);
			await CommonUtils.sleep(2);
			await PwActions.click(page, targetRadioBtn);
			await CommonUtils.sleep(2);
			await PwActions.waitForNetworkIdle(page, 20000);
			await PwActions.waitForElement(page, updateAnonymityDialog);
			if (await PwActions.elementIsVisible(page, updateAnonymityDialog)) {
				await PwActions.click(page, this.btnConfirmAndApplyOverrideAnonymity);
				await CommonUtils.sleep(2);
			}
		}

		// Dropdown to select Roles/Names only exists in Non Anonymous mode
		if (showNameOrRole && !isAnonymous) {
			await PwActions.waitForNetworkIdle(page, 20000);
			await PwActions.waitForElement(page, this.dropDownShowNameOrRole);
			await CommonUtils.sleep(4);
			await PwActions.waitForNetworkIdle(page, 20000);
			await PwActions.forceClick(page, this.dropDownShowNameOrRole);
			await PwActions.waitForElementVisibility(page, this.optionRoles);
			await CommonUtils.sleep(4);
			await PwActions.click(
				page,
				roleOrName === "Names" ? this.optionNames : this.optionRoles,
			);
		}

		if (override?.length) {
			await PwActions.waitForElement(page, this.btnOverrideAnonymity);
			await PwActions.click(page, this.btnOverrideAnonymity);
			await PwActions.waitForElementVisibility(
				page,
				this.txtModalOverrideAnonymity,
			);

			for (const item of override) {
				const overrideOption =
					item.anonymity === "Show Roles"
						? this.optionOverrideRoles
						: item.anonymity === "Show Names"
							? this.optionOverrideNames
							: this.optionOverrideAnonymous;
				await PwActions.click(
					page,
					this.dropDownOverrideAnonymity(item.question),
				);
				await PwActions.waitForElementVisibility(page, overrideOption);

				await PwActions.click(page, overrideOption);
				await CommonUtils.sleep(2);
			}

			await PwActions.click(page, this.btnSaveOverrideAnonymity);
		}
		await PwActions.waitForNetworkIdle(page, 20000);
		await PwActions.waitForElementVisibility(page, this.sideBarAnonymity);
		await PwActions.click(page, this.sideBarAnonymity);
		await CommonUtils.sleep(8);
	}

	/**
	 * Verifies the evaluator anonymity settings
	 * @param {object} anonymitySettings - The anonymity settings to verify
	 * @param {string} anonymitySettings.anonymity - The anonymity type ("Anonymous" | "Non Anonymous")
	 * @param {boolean} [anonymitySettings.showNameOrRole] - Whether to show name/role of evaluators in feedback report
	 * - For "Non Anonymous": verifies "Show [Roles/Names] of the evaluators" or "Do not show roles and names"
	 * - For "Anonymous": verifies "Show roles of the evaluators" or "Do not show roles of the evaluators"
	 * @param {string} [anonymitySettings.roleOrName] - What to display ("Roles" | "Names"). Only applicable when anonymity is "Non Anonymous" and showNameOrRole is true
	 * @param {Array<{question: string, anonymity: string}>} [anonymitySettings.override] - Question-specific anonymity overrides
	 * @example
	 * // Verify Non Anonymous with Roles shown
	 * await configurePage.verifyEvaluatorAnonymitySettings({
	 * 	anonymitySettings: { anonymity: "Non Anonymous", showNameOrRole: true, roleOrName: "Roles" }
	 * });
	 * @example
	 * // Verify Anonymous with roles shown
	 * await configurePage.verifyEvaluatorAnonymitySettings({
	 * 	anonymitySettings: { anonymity: "Anonymous", showNameOrRole: true }
	 * });
	 * @example
	 * // Verify with override settings
	 * await configurePage.verifyEvaluatorAnonymitySettings({
	 * 	anonymitySettings: {
	 * 		anonymity: "Non Anonymous",
	 * 		showNameOrRole: true,
	 * 		override: [{ question: "Please explain the reason for your scores?", anonymity: "Show Names" }]
	 * 	}
	 * });
	 */
	async verifyEvaluatorAnonymitySettings({
		anonymitySettings,
		page = this.page,
	}) {
		const { anonymity, showNameOrRole, roleOrName, override } =
			anonymitySettings ?? {};
		const isAnonymous = anonymity === "Anonymous";

		await PwActions.click(page, this.sideBarAnonymity);
		await PwActions.waitTillVisible(page, this.dropdownAnonymity);

		if (anonymity) {
			await PwActions.verifyElementIsPresent(
				page,
				this.txtEvaluatorAnonymity(anonymity),
			);
		}

		await this.commonfunction.verifyCheckboxChecked(
			this.getAnonymityRadioButton(isAnonymous, showNameOrRole),
			page,
		);

		// Dropdown to select Roles/Names only exists in Non Anonymous mode
		if (showNameOrRole && !isAnonymous) {
			await PwActions.verifyElementIsPresent(
				page,
				this.txtShowNameOrRole(roleOrName),
			);
		}

		if (override?.length) {
			await PwActions.waitForElement(page, this.btnOverrideAnonymity);
			await PwActions.click(page, this.btnOverrideAnonymity);
			await PwActions.waitForElementVisibility(
				page,
				this.txtModalOverrideAnonymity,
			);
			await CommonUtils.sleep(2);

			for (const item of override) {
				await PwActions.verifyElementIsPresent(
					page,
					this.txtOverrideAnonymity(item.question, item.anonymity),
				);
			}
			await PwActions.click(page, this.btnCloseOverrideAnonymityModal);
		}
	}

