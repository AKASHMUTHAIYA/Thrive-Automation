	/**
	 * Changes the normalization point scale in the Configure > Review Settings page.
	 * This setting determines the default score scale to which all rating scales are normalized.
	 *
	 * @param {Object} options - Configuration options
	 * @param {string} options.pointScale - The point scale value to select (e.g., "Point 3", "Point 5", "Point 8")
	 * @param {import('@playwright/test').Page} [options.page=this.page] - The Playwright page object
	 * @returns {Promise<void>}
	 *
	 * @example
	 * // Change normalization to 5-point scale
	 * await performanceConfigurePage.changeNormalizationPointScale({ pointScale: "Point 5" });
	 *
	 * @example
	 * // Change normalization to 3-point scale with explicit page
	 * await performanceConfigurePage.changeNormalizationPointScale({
	 *   page: customPage,
	 *   pointScale: "Point 3"
	 * });
	 */
	async changeNormalizationPointScale({ page = this.page, pointScale }) {
		await PwActions.click(page, this.btnReviewSettings);
		await PwActions.waitForNetworkIdle(page, 10000);
		await CommonUtils.sleep(1);

		await PwActions.scroll(page, this.drpdwnNormalizationPointScale);
		await PwActions.click(page, this.drpdwnNormalizationPointScale);
		await CommonUtils.sleep(1);
		await PwActions.click(
			page,
			this.getNormalizationPointScaleOption(pointScale),
		);
		await PwActions.waitForNetworkIdle(page, 10000);
		await CommonUtils.sleep(1);
		await PwActions.waitForElement(page, this.btnProceedScoreUpdate);
		await PwActions.click(page, this.btnProceedScoreUpdate);

		const selectedValue = await PwActions.getText(
			page,
			this.txtNormalizationPointScaleValue,
		);
		expect(
			selectedValue,
			`Normalization point scale should be set to ${pointScale}`,
		).toBe(pointScale);
		await PwActions.pageRefresh(page);
	}
