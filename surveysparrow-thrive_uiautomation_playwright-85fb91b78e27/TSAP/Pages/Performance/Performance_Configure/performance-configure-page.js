	/**
	 * Adds a custom competency with the specified name and description for subject and group report
	 * @param {string} competencyName - Name of the competency to add
	 * @param {string} competencyDescription - Description of the competency
	 * @param {object} settings - Settings for the competency
	 * @example
	 * const competencyDetails = await configurePage.addCustomCompetency(
	 * 	"Competency on Subject Report",
	 * 	"This is an competency done on Subject Report",
	 * 	{
	 * 		reportType: constants.REPORT_TYPES.SUBJECT_REPORT,
	 * 		addQuestions: true,
	 * 		uncheckAlreadyAddedQuestions: true,
	 * 		showBenchMark: true,
	 * 	},
	 * );
	 *
	 * Both uncheckAlreadyAddedQuestion and showBenchMark can be accessed from otherSettings object like this:
	 * otherSettings.uncheckAlreadyAddedQuestions
	 * otherSettings.showBenchMark
	 */

	async addCustomCompetency(
		competencyName,
		competencyDescription = "",
		{ reportType = undefined, addQuestions = false, ...otherSettings } = {},
	) {
		try {
			const questionsData = {
				sectionName: competencyName,
				questions: [],
			};
			const reportTypeToButton = {
				[constants.REPORT_TYPES.SUBJECT_AND_GROUP_REPORT]:
					this.btnToSubjectAndGroupReport,
				[constants.REPORT_TYPES.SUBJECT_REPORT]: this.btnToSubjectReport,
				[constants.REPORT_TYPES.GROUP_REPORT]: this.btnToGroupReport,
			};
			const buttonSelector = reportTypeToButton[reportType];
			if (!buttonSelector) throw new Error("Invalid report type");

			await PwActions.click(this.page, this.btnAddCompetency);
			await PwActions.click(this.page, buttonSelector);
			await PwActions.fill(this.page, this.inputCompetencyName, competencyName);

			if (competencyDescription) {
				await PwActions.fill(
					this.page,
					this.inputCompetencyDescription,
					competencyDescription,
				);
			}

			if (addQuestions) {
				await PwActions.click(this.page, this.btnAddQuestions);
				if (otherSettings.sectionNameForQuestions) {
					questionsData.sectionName = otherSettings.sectionNameForQuestions;
				} else {
					const sectionNamesText = await PwActions.getElementsText(
						this.page,
						await PwActions.getWebElementsPage(
							this.page,
							this.webElementsAllSections,
						),
					);
					questionsData.sectionName = generateRandomName(sectionNamesText);
				}
				await PwActions.click(
					this.page,
					this.getCheckboxForSection(questionsData.sectionName),
				);
				const questionsList = await PwActions.getElementsText(
					this.page,
					await PwActions.getWebElementsPage(
						this.page,
						this.getSelectedQuestionElementsForCompetency,
					),
				);

				questionsData.questions = questionsList;
				await PwActions.click(this.page, this.btnAdd);
			}

			await PwActions.click(this.page, this.btnCreate);
			await PwActions.waitTillVisible(
				this.page,
				this.toasterCompetencySuccessfullyCreated,
			);

			return { competencyName, reportType, questions: questionsData };
		} catch (error) {
			console.error("Error in addCustomCompetency:", error);
			throw error;
		}
	}

